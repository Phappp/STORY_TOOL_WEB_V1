$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$python = Join-Path $root '.venv\Scripts\python.exe'
if (-not (Test-Path $python)) { throw "Project virtualenv Python was not found: $python" }

# Pin the certificate observed on this host and verified in LocalMachine\Root.
# Export only the public root certificate; never export its private key.
$thumbprint = '483F46B34645C31A9C4DDA044C7DA3989C770AC2'
$expectedSubject = 'CN=Avast Web/Mail Shield Root, O=Avast Web/Mail Shield, OU=generated by Avast Antivirus for SSL/TLS scanning'
$certificate = Get-Item "Cert:\LocalMachine\Root\$thumbprint" -ErrorAction SilentlyContinue
if (-not $certificate) {
  Write-Host 'Pinned TLS inspection CA is not present in LocalMachine Root; leaving pip certificate settings unchanged.'
  exit 0
}
if ($certificate.Subject -ne $expectedSubject -or $certificate.Subject -ne $certificate.Issuer) {
  throw 'The certificate matching the pinned thumbprint is not the expected self-signed trusted root.'
}

$certificateDirectory = Join-Path $root '.venv\certs'
New-Item -ItemType Directory -Force -Path $certificateDirectory | Out-Null
$derPath = Join-Path $certificateDirectory 'windows-trusted-root.der'
$bundlePath = Join-Path $certificateDirectory 'pip-ca-bundle.pem'
[IO.File]::WriteAllBytes($derPath, $certificate.RawData)
$bundleBuilder = Join-Path $PSScriptRoot 'build-pip-ca-bundle.py'
& $python $bundleBuilder $derPath $bundlePath
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $bundlePath)) { throw 'Could not build the per-venv pip CA bundle.' }
& $python -m pip config --site set global.cert $bundlePath
if ($LASTEXITCODE -ne 0) { throw 'Could not configure the project-venv pip CA bundle.' }
